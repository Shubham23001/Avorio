export function DataTableDemo() {
  const [sorting, setSorting] = React.useState<SortingState>([]);
  const [columnFilters, setColumnFilters] = React.useState<ColumnFiltersState>([]);
  const [columnVisibility, setColumnVisibility] = React.useState<VisibilityState>({});
  const [rowSelection, setRowSelection] = React.useState<Record<string, boolean>>({});
  const [dataState, setDataState] = React.useState<Payment[]>(data);

  const table = useReactTable({
    data: dataState,
    columns,
    onSortingChange: setSorting,
    onColumnFiltersChange: setColumnFilters,
    getCoreRowModel: getCoreRowModel(),
    getPaginationRowModel: getPaginationRowModel(),
    getSortedRowModel: getSortedRowModel(),
    getFilteredRowModel: getFilteredRowModel(),
    onColumnVisibilityChange: setColumnVisibility,
    onRowSelectionChange: setRowSelection,
    state: {
      sorting,
      columnFilters,
      columnVisibility,
      rowSelection,
    },
  });

  // Prepare columns and data for CommonTable
  const tableData = getTableData<Payment>(table);
  const commonTableColumns = mapReactTableToCommonColumns<Payment>(table);

  // Map rowSelection object to array of selected row indices
  const selectedRows = table.getRowModel().rows
    .map((row, idx) => (row.getIsSelected() ? idx : -1))
    .filter(idx => idx !== -1);

  // Handle row selection change for CommonTable
  const handleRowSelectChange = (rowIdx: number, checked: boolean) => {
    const row = table.getRowModel().rows[rowIdx];
    if (!row) return;
    row.toggleSelected(checked);
  };

  // Handle bulk delete
  const handleBulkDelete = (selected: number[]) => {
    const idsToDelete = selected.map(idx => table.getRowModel().rows[idx]?.original.id);
    setDataState(prev => prev.filter(row => !idsToDelete.includes(row.id)));
    // Optionally clear selection
    setRowSelection({});
  };

  return (
    <div className="w-full">
      <TableToolbar table={table} filterColumnKey="email" filterPlaceholder="Filter emails..." />
      <div className="overflow-hidden rounded-md border">
        <CommonTable
          columns={commonTableColumns}
          data={tableData}
          selectable
          selectedRows={selectedRows}
          onRowSelectChange={handleRowSelectChange}
          onBulkDelete={handleBulkDelete}
        />
      </div>
      <TablePaginationFooter table={table} />
    </div>
  );
}

export default DataTableDemo
